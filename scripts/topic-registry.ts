/**
 * The two mechanical parts of adding a topic: its place in `topics/topics.json`, and its
 * row in the root README's topic table, which is generated between markers by the build.
 */

export interface TableTopic { id: string; number: string; title: string; description: string; documents: { file: string; title: string }[] }

const start = '<!-- topics:start (generated by npm run build from topics/topics.json and each topic\'s front matter; do not edit) -->';
const end = '<!-- topics:end -->';
// Backslashes are escaped with the characters they could otherwise neutralise.
const oneLine = (text: string) => text.replace(/\s+/g, ' ').trim();
const cell = (text: string) => oneLine(text).replace(/[\\|]/g, '\\$&');
const label = (text: string) => oneLine(text).replace(/[\\|[\]]/g, '\\$&');

export function topicTable(siteUrl: string, topics: TableTopic[]): string {
  const rows = topics.map(topic => {
    const sources = topic.documents.map((doc, index) => `[${index === 0 ? 'README' : label(doc.title)}](topics/${topic.id}/${doc.file})`).join(' · ');
    return `| **${topic.number} · ${cell(topic.title)}** | ${cell(topic.description)} | ${sources} | [Read online](${new URL(`topics/${topic.id}/`, siteUrl).href}) |`;
  });
  return [start, '| Topic | Idea | Markdown | Interactive edition |', '| --- | --- | --- | --- |', ...rows, end].join('\n');
}

/** Replaces the generated block; the README must contain exactly one pair of markers. */
export function withTopicTable(readme: string, table: string): string {
  const from = readme.indexOf('<!-- topics:start'), to = readme.indexOf(end);
  if (from < 0 || to < from || readme.indexOf('<!-- topics:start', from + 1) >= 0 || readme.indexOf(end, to + 1) >= 0) {
    throw new Error('README.md needs exactly one <!-- topics:start … --> … <!-- topics:end --> block for the generated topic table.');
  }
  return readme.slice(0, from) + table + readme.slice(to + end.length);
}

/** Appends an ID to the `topics` array, keeping the file's hand-written formatting. */
export function registerTopic(json: string, id: string): string {
  const registry = JSON.parse(json) as { topics?: unknown };
  if (!Array.isArray(registry.topics)) throw new Error('topics/topics.json has no "topics" array.');
  if (registry.topics.includes(id)) return json;
  const match = /("topics"\s*:\s*\[)([\s\S]*?)(\s*)\]/.exec(json);
  if (!match) throw new Error('Could not find the "topics" array in topics/topics.json.');
  const [whole, opening, items, closing] = match;
  const indent = /\n([ \t]*)"/.exec(items)?.[1] ?? '  ';
  const entry = JSON.stringify(id);
  const updated = items.trim() ? `${opening}${items},\n${indent}${entry}${closing}]` : `${opening}\n${indent}${entry}${closing || '\n'}]`;
  const result = json.slice(0, match.index) + updated + json.slice(match.index + whole.length);
  const parsed = JSON.parse(result) as { topics: string[] };
  if (JSON.stringify(parsed.topics) !== JSON.stringify([...registry.topics, id])) throw new Error('Registering the topic would change other topics.json content.');
  return result;
}
